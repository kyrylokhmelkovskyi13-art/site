create table if not exists public.botcontrol_applications (
  id bigint generated by default as identity primary key,
  applicant_discord_id text not null,
  applicant_username text not null,
  bot_name text not null,
  bot_discord_id text not null,
  description text not null,
  invite_url text not null,
  avatar_url text,
  support_url text,
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected')),
  reviewed_by text,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists botcontrol_applications_applicant_created_idx
  on public.botcontrol_applications (applicant_discord_id, created_at desc);

alter table public.botcontrol_applications enable row level security;

-- BotControl accesses this table from its backend with the Supabase service-role key.
-- Do not expose the service-role key in browser code.
